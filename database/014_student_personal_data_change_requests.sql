-- Student personal-data change workflow (national ID only)
-- Run once in the shared Supabase project used by both portals.

CREATE TABLE IF NOT EXISTS public.student_personal_data_change_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  national_id TEXT NOT NULL,
  student_name TEXT,
  original_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  requested_changes JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','approved','rejected','needs_more_info')),
  reason TEXT NOT NULL DEFAULT 'طلب تعديل بيانات مقدم من الطالب',
  reviewer_employee_id BIGINT,
  reviewer_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ
);

-- Upgrade safely if the earlier seating-number/one-field table was already created.
ALTER TABLE public.student_personal_data_change_requests
  ADD COLUMN IF NOT EXISTS national_id TEXT,
  ADD COLUMN IF NOT EXISTS student_name TEXT,
  ADD COLUMN IF NOT EXISTS original_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS requested_changes JSONB NOT NULL DEFAULT '{}'::jsonb;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='student_personal_data_change_requests' AND column_name='student_id') THEN
    ALTER TABLE public.student_personal_data_change_requests ALTER COLUMN student_id DROP NOT NULL;
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='student_personal_data_change_requests' AND column_name='field_name') THEN
    ALTER TABLE public.student_personal_data_change_requests ALTER COLUMN field_name DROP NOT NULL;
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='student_personal_data_change_requests' AND column_name='requested_value') THEN
    ALTER TABLE public.student_personal_data_change_requests ALTER COLUMN requested_value DROP NOT NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_personal_change_requests_status_created
  ON public.student_personal_data_change_requests(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_personal_change_requests_national_id
  ON public.student_personal_data_change_requests(national_id, created_at DESC);

ALTER TABLE public.student_personal_data_change_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.student_personal_data_change_requests FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.student_personal_data_change_requests TO service_role;

-- Remove the obsolete seating-number overload if an earlier draft was installed.
DROP FUNCTION IF EXISTS public.submit_student_personal_data_change_request(TEXT, TEXT, JSONB);

-- Submit a single request containing all changed fields. No student record is changed here.
CREATE OR REPLACE FUNCTION public.submit_student_personal_data_change_request(
  p_national_id TEXT,
  p_changes JSONB
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_student RECORD;
  v_change JSONB;
  v_field TEXT;
  v_original JSONB := '{}'::jsonb;
  v_requested JSONB := '{}'::jsonb;
  v_allowed TEXT[] := ARRAY[
    'gender','nationality','birth_date','birth_place','phone_number',
    'whatsapp_number','address','directorate_name','school_name','branch'
  ];
  v_request_id BIGINT;
BEGIN
  IF NULLIF(TRIM(p_national_id), '') IS NULL OR TRIM(p_national_id) !~ '^[0-9]{9}$' THEN
    RAISE EXCEPTION 'رقم الهوية يجب أن يتكون من 9 أرقام';
  END IF;
  IF jsonb_typeof(p_changes) <> 'array' OR jsonb_array_length(p_changes) = 0 THEN
    RAISE EXCEPTION 'لا توجد تعديلات لإرسالها';
  END IF;

  SELECT a.* INTO v_student
  FROM public.allow_student a
  WHERE TRIM(a.national_id::text) = TRIM(p_national_id)
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'رقم الهوية غير مؤهل للتسجيل أو غير موجود';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.student_personal_data_change_requests r
    WHERE r.national_id = TRIM(p_national_id)
      AND r.status IN ('pending','needs_more_info')
  ) THEN
    RAISE EXCEPTION 'يوجد طلب تعديل قيد المراجعة بالفعل';
  END IF;

  FOR v_change IN SELECT value FROM jsonb_array_elements(p_changes)
  LOOP
    v_field := v_change->>'field_name';
    IF NOT (v_field = ANY(v_allowed)) THEN
      RAISE EXCEPTION 'حقل التعديل غير مسموح: %', v_field;
    END IF;
    IF NOT (to_jsonb(v_student) ? v_field) THEN
      RAISE EXCEPTION 'الحقل غير موجود في بيانات الطالب: %', v_field;
    END IF;
    v_original := v_original || jsonb_build_object(v_field, to_jsonb(v_student)->v_field);
    v_requested := v_requested || jsonb_build_object(v_field, COALESCE(v_change->'requested_value', 'null'::jsonb));
  END LOOP;

  INSERT INTO public.student_personal_data_change_requests
    (national_id, student_name, original_data, requested_changes)
  VALUES
    (TRIM(p_national_id), COALESCE(to_jsonb(v_student)->>'full_name_ar', to_jsonb(v_student)->>'student_name'), v_original, v_requested)
  RETURNING id INTO v_request_id;

  RETURN v_request_id;
END;
$$;

-- Only active registrar/Admin employee can list requests.
CREATE OR REPLACE FUNCTION public.list_student_personal_data_change_requests(p_employee_id BIGINT)
RETURNS SETOF public.student_personal_data_change_requests
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.employees e
    LEFT JOIN public.jobs j ON j.id = e.job_id
    WHERE e.id = p_employee_id
      AND COALESCE(e.is_active, TRUE) = TRUE
      AND (TRIM(COALESCE(j.job_name, e.role, '')) = 'مسجل'
           OR TRIM(COALESCE(e.role, '')) = 'Admin')
  ) THEN
    RAISE EXCEPTION 'غير مصرح لك بعرض طلبات تعديل البيانات';
  END IF;
  RETURN QUERY SELECT * FROM public.student_personal_data_change_requests ORDER BY created_at DESC;
END;
$$;

-- Apply requested values to allow_student only after registrar approval.
CREATE OR REPLACE FUNCTION public.review_student_personal_data_request(
  p_request_id BIGINT,
  p_employee_id BIGINT,
  p_decision TEXT,
  p_note TEXT DEFAULT NULL
) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_request public.student_personal_data_change_requests%ROWTYPE;
  v_field TEXT;
  v_value JSONB;
  v_allowed TEXT[] := ARRAY[
    'gender','nationality','birth_date','birth_place','phone_number',
    'whatsapp_number','address','directorate_name','school_name','branch'
  ];
  v_type TEXT;
BEGIN
  IF p_decision NOT IN ('approved','rejected','needs_more_info') THEN
    RAISE EXCEPTION 'قرار المراجعة غير صالح';
  END IF;
  IF p_decision IN ('rejected','needs_more_info') AND NULLIF(TRIM(p_note), '') IS NULL THEN
    RAISE EXCEPTION 'الملاحظة مطلوبة عند الرفض أو طلب الاستكمال';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.employees e
    LEFT JOIN public.jobs j ON j.id = e.job_id
    WHERE e.id = p_employee_id
      AND COALESCE(e.is_active, TRUE) = TRUE
      AND (TRIM(COALESCE(j.job_name, e.role, '')) = 'مسجل'
           OR TRIM(COALESCE(e.role, '')) = 'Admin')
  ) THEN
    RAISE EXCEPTION 'غير مصرح لك بمراجعة طلبات تعديل البيانات';
  END IF;

  SELECT * INTO v_request
  FROM public.student_personal_data_change_requests
  WHERE id = p_request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'الطلب غير موجود'; END IF;
  IF v_request.status NOT IN ('pending','needs_more_info') THEN
    RAISE EXCEPTION 'تمت مراجعة هذا الطلب مسبقاً';
  END IF;

  IF p_decision = 'approved' THEN
    FOR v_field, v_value IN SELECT key, value FROM jsonb_each(v_request.requested_changes)
    LOOP
      IF NOT (v_field = ANY(v_allowed)) THEN RAISE EXCEPTION 'حقل غير مسموح: %', v_field; END IF;
      SELECT data_type INTO v_type
      FROM information_schema.columns
      WHERE table_schema='public' AND table_name='allow_student' AND column_name=v_field;
      IF v_type IS NULL THEN RAISE EXCEPTION 'الحقل % غير موجود في allow_student', v_field; END IF;

      IF v_field = 'birth_date' THEN
        EXECUTE format('UPDATE public.allow_student SET %I = NULLIF($1, '''')::date WHERE TRIM(national_id::text) = $2', v_field)
          USING CASE WHEN v_value = 'null'::jsonb THEN NULL ELSE v_value #>> '{}' END, v_request.national_id;
      ELSE
        EXECUTE format('UPDATE public.allow_student SET %I = $1 WHERE TRIM(national_id::text) = $2', v_field)
          USING CASE WHEN v_value = 'null'::jsonb THEN NULL ELSE v_value #>> '{}' END, v_request.national_id;
      END IF;
    END LOOP;
  END IF;

  UPDATE public.student_personal_data_change_requests
  SET status=p_decision, reviewer_employee_id=p_employee_id,
      reviewer_note=NULLIF(TRIM(p_note), ''), reviewed_at=NOW()
  WHERE id=p_request_id;
  RETURN TRUE;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_student_personal_data_change_request(TEXT, JSONB) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.list_student_personal_data_change_requests(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.review_student_personal_data_request(BIGINT, BIGINT, TEXT, TEXT) FROM PUBLIC;
