-- ============================================================
-- طلبات مراجعة امتحانات الطلاب - الصف 12
-- دورة الطلب: Student + Subject + Exam Cycle = طلب واحد فقط
-- ============================================================

ALTER TABLE public.exams ADD COLUMN IF NOT EXISTS cycle_id bigint;

CREATE TABLE IF NOT EXISTS public.exam_review_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id bigint NOT NULL,
  exam_id bigint NOT NULL,
  subject_id bigint NOT NULL,
  branch_id bigint NOT NULL,
  cycle_id bigint NOT NULL,
  original_score numeric(10,2) NOT NULL DEFAULT 0,
  reviewed_score numeric(10,2),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','reviewed_correct','reviewed_adjusted')),
  reviewer_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(student_id, subject_id, cycle_id)
);

CREATE INDEX IF NOT EXISTS idx_exam_review_requests_scope ON public.exam_review_requests(branch_id, subject_id, cycle_id, status);
CREATE INDEX IF NOT EXISTS idx_exam_review_requests_student ON public.exam_review_requests(student_id, cycle_id);

CREATE TABLE IF NOT EXISTS public.exam_review_question_scores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES public.exam_review_requests(id) ON DELETE CASCADE,
  question_id bigint NOT NULL,
  original_score numeric(10,2) NOT NULL DEFAULT 0,
  reviewed_score numeric(10,2) NOT NULL DEFAULT 0,
  reviewer_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(request_id, question_id)
);

CREATE TABLE IF NOT EXISTS public.exam_review_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL,
  student_id bigint NOT NULL,
  exam_id bigint NOT NULL,
  subject_id bigint NOT NULL,
  branch_id bigint NOT NULL,
  cycle_id bigint NOT NULL,
  question_id bigint,
  action text NOT NULL,
  old_score numeric(10,2),
  new_score numeric(10,2),
  reviewer_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_exam_review_audit_request ON public.exam_review_audit(request_id, created_at DESC);

-- إنشاء الطلب من بوابة الطالب: يتحقق من وجود تسليم فعلي، ومن دورة الطالب، ومن عدم تكرار الطلب.
CREATE OR REPLACE FUNCTION public.create_exam_review_request(
  p_student_id bigint,
  p_exam_id bigint
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE s record; e record; r record; cycle_no bigint; score numeric; sid bigint; branch_id_val bigint; subject_id_val bigint;
BEGIN
  SELECT * INTO s FROM public.students WHERE id=p_student_id LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'الطالب غير موجود'; END IF;

  SELECT * INTO e FROM public.exams WHERE id=p_exam_id LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'الامتحان غير موجود'; END IF;

  IF NOT EXISTS (SELECT 1 FROM public.submissions WHERE student_id=p_student_id AND exam_id=p_exam_id) THEN
    RAISE EXCEPTION 'لا يمكن تقديم طلب مراجعة لامتحان لم يتم تسليمه';
  END IF;

  cycle_no := COALESCE(e.cycle_id, s.registration_cycle);
  IF cycle_no IS NULL OR s.registration_cycle IS NULL OR cycle_no <> s.registration_cycle THEN
    RAISE EXCEPTION 'لا يمكن تقديم طلب مراجعة إلا لامتحان الدورة الحالية للطالب';
  END IF;

  branch_id_val := COALESCE(e.branch_id, NULLIF(to_jsonb(s)->>'branch_id','')::bigint);
  subject_id_val := e.subject_id;
  IF branch_id_val IS NULL OR subject_id_val IS NULL THEN RAISE EXCEPTION 'بيانات فرع أو مادة الامتحان غير مكتملة'; END IF;

  SELECT COALESCE(er.final_score, sub.final_score, sub.obtained_marks, sub.total_score, 0) INTO score
  FROM public.submissions sub
  LEFT JOIN public.exam_results er ON er.student_id=sub.student_id AND er.exam_id=sub.exam_id
  WHERE sub.student_id=p_student_id AND sub.exam_id=p_exam_id
  ORDER BY sub.id DESC LIMIT 1;

  INSERT INTO public.exam_review_requests(student_id,exam_id,subject_id,branch_id,cycle_id,original_score,reviewed_score)
  VALUES(p_student_id,p_exam_id,subject_id_val,branch_id_val,cycle_no,COALESCE(score,0),NULL)
  RETURNING * INTO r;

  RETURN jsonb_build_object('id',r.id,'student_id',r.student_id,'exam_id',r.exam_id,'subject_id',r.subject_id,'branch_id',r.branch_id,'cycle_id',r.cycle_id,'original_score',r.original_score,'status',r.status);
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION 'لقد سبق لك تقديم طلب مراجعة لهذه المادة في هذه الدورة';
END;
$$;

-- فحص صلاحية المراجع: المدير يرى الجميع، والمراجع لا يرى إلا الفرع والمادة المكلف بهما.
CREATE OR REPLACE FUNCTION public.can_review_exam_request(p_employee_id bigint, p_request_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.employees e
    JOIN public.exam_review_requests r ON r.id=p_request_id
    LEFT JOIN public.jobs j ON j.id=e.job_id
    WHERE e.id=p_employee_id
      AND e.is_active IS DISTINCT FROM false
      AND (
        lower(coalesce(to_jsonb(e)->>'role','')) IN ('admin','manager','مدير')
        OR lower(coalesce(j.job_name,''))='مدير'
        OR (r.branch_id=e.branch_id AND r.subject_id=e.subject_id AND EXISTS (
          SELECT 1 FROM public.job_permissions jp
          JOIN public.permissions pp ON pp.id=jp.permission_id
          WHERE jp.job_id=e.job_id AND pp.permission_key='review_exam_requests'
        ))
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.complete_exam_review_correct(p_request_id bigint, p_reviewer_id bigint)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE r record;
BEGIN
  IF NOT public.can_review_exam_request(p_reviewer_id,p_request_id) THEN RAISE EXCEPTION 'لا تملك صلاحية مراجعة هذا الامتحان'; END IF;
  SELECT * INTO r FROM public.exam_review_requests WHERE id=p_request_id AND status='pending' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'طلب المراجعة غير موجود أو تمت مراجعته مسبقاً'; END IF;

  UPDATE public.exam_review_requests SET status='reviewed_correct', reviewed_score=original_score, reviewer_id=p_reviewer_id, reviewed_at=now(), updated_at=now() WHERE id=p_request_id;
  INSERT INTO public.exam_review_audit(request_id,student_id,exam_id,subject_id,branch_id,cycle_id,action,old_score,new_score,reviewer_id)
  VALUES(r.id,r.student_id,r.exam_id,r.subject_id,r.branch_id,r.cycle_id,'علامة صحيحة',r.original_score,r.original_score,p_reviewer_id);
  RETURN jsonb_build_object('success',true,'reviewed_score',r.original_score);
END;
$$;

CREATE OR REPLACE FUNCTION public.apply_exam_review_adjustment(
  p_request_id bigint,
  p_question_id bigint,
  p_new_score numeric,
  p_reviewer_id bigint
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE r record; q record; oldq numeric; new_total numeric; max_exam numeric; avgm numeric;
BEGIN
  IF NOT public.can_review_exam_request(p_reviewer_id,p_request_id) THEN RAISE EXCEPTION 'لا تملك صلاحية تعديل هذا الامتحان'; END IF;
  SELECT * INTO r FROM public.exam_review_requests WHERE id=p_request_id AND status='pending' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'طلب المراجعة غير موجود أو تمت مراجعته مسبقاً'; END IF;

  SELECT * INTO q FROM public.questions WHERE id=p_question_id LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'السؤال غير موجود'; END IF;

  max_exam := COALESCE((SELECT total_marks FROM public.exams WHERE id=r.exam_id LIMIT 1),0);
  oldq := COALESCE((SELECT reviewed_score FROM public.exam_review_question_scores WHERE request_id=r.id AND question_id=p_question_id),
                   (SELECT COALESCE(
                      NULLIF(to_jsonb(sa)->>'mark','')::numeric,
                      NULLIF(to_jsonb(sa)->>'marks','')::numeric,
                      NULLIF(to_jsonb(sa)->>'score','')::numeric,
                      NULLIF(to_jsonb(sa)->>'earned_marks','')::numeric,
                      NULLIF(to_jsonb(sa)->>'earned_score','')::numeric,
                      0)
                    FROM public.student_answers sa
                    WHERE sa.student_id=r.student_id AND sa.exam_id=r.exam_id AND sa.question_id=p_question_id
                    ORDER BY sa.id DESC LIMIT 1),0);

  IF p_new_score < 0 OR p_new_score > COALESCE(
      NULLIF(to_jsonb(q)->>'mark','')::numeric,
      NULLIF(to_jsonb(q)->>'marks','')::numeric,
      NULLIF(to_jsonb(q)->>'points','')::numeric,
      NULLIF(to_jsonb(q)->>'score','')::numeric,
      NULLIF(to_jsonb(q)->>'degree','')::numeric,
      NULLIF(to_jsonb(q)->>'question_mark','')::numeric,
      0) THEN
    RAISE EXCEPTION 'علامة السؤال خارج الحد المسموح';
  END IF;

  INSERT INTO public.exam_review_question_scores(request_id,question_id,original_score,reviewed_score,reviewer_id)
  VALUES(r.id,p_question_id,oldq,p_new_score,p_reviewer_id)
  ON CONFLICT(request_id,question_id) DO UPDATE SET reviewed_score=EXCLUDED.reviewed_score, reviewer_id=p_reviewer_id, updated_at=now();

  new_total := r.original_score + COALESCE((SELECT SUM(reviewed_score-original_score) FROM public.exam_review_question_scores WHERE request_id=r.id),0);
  IF max_exam > 0 THEN new_total := LEAST(GREATEST(new_total,0),max_exam); END IF;
  avgm := CASE WHEN max_exam > 0 THEN round((new_total/max_exam)*100,2) ELSE 0 END;

  UPDATE public.exam_review_requests SET status='pending', reviewed_score=new_total, reviewer_id=p_reviewer_id, updated_at=now() WHERE id=r.id;
  UPDATE public.submissions SET final_score=new_total, obtained_marks=new_total, average=avgm, score_updated_at=now() WHERE student_id=r.student_id AND exam_id=r.exam_id;
  UPDATE public.exam_results SET final_score=new_total, average=avgm, updated_at=now() WHERE student_id=r.student_id AND exam_id=r.exam_id;

  INSERT INTO public.exam_review_audit(request_id,student_id,exam_id,subject_id,branch_id,cycle_id,question_id,action,old_score,new_score,reviewer_id)
  VALUES(r.id,r.student_id,r.exam_id,r.subject_id,r.branch_id,r.cycle_id,p_question_id,'تعديل علامة السؤال',oldq,p_new_score,p_reviewer_id);

  RETURN jsonb_build_object('success',true,'reviewed_score',new_total,'average',avgm);
END;
$$;

CREATE OR REPLACE FUNCTION public.finalize_exam_review_adjusted(p_request_id bigint, p_reviewer_id bigint)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE r record;
BEGIN
  IF NOT public.can_review_exam_request(p_reviewer_id,p_request_id) THEN RAISE EXCEPTION 'لا تملك صلاحية اعتماد هذا الامتحان'; END IF;
  SELECT * INTO r FROM public.exam_review_requests WHERE id=p_request_id AND status='pending' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'طلب المراجعة غير موجود أو تمت مراجعته مسبقاً'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.exam_review_question_scores WHERE request_id=r.id AND reviewer_id=p_reviewer_id) THEN
    RAISE EXCEPTION 'لم يتم تعديل أي سؤال';
  END IF;
  UPDATE public.exam_review_requests SET status='reviewed_adjusted', reviewer_id=p_reviewer_id, reviewed_at=now(), updated_at=now() WHERE id=r.id;
  INSERT INTO public.exam_review_audit(request_id,student_id,exam_id,subject_id,branch_id,cycle_id,action,old_score,new_score,reviewer_id)
  VALUES(r.id,r.student_id,r.exam_id,r.subject_id,r.branch_id,r.cycle_id,'اعتماد التعديلات',r.original_score,r.reviewed_score,p_reviewer_id);
  RETURN jsonb_build_object('success',true,'reviewed_score',r.reviewed_score);
END;
$$;

-- قراءة آمنة للطلب من بوابة الطالب، وتعيد فقط بيانات طلب الطالب نفسه.
CREATE OR REPLACE FUNCTION public.get_student_review_requests(p_student_id bigint)
RETURNS SETOF public.exam_review_requests
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT r.* FROM public.exam_review_requests r WHERE r.student_id=p_student_id ORDER BY r.cycle_id DESC, r.created_at DESC;
$$;

