-- إضافة وظيفة المراجع عند الحاجة، ومنحها صلاحيات المراجعة.
DO $$
DECLARE reviewer_job_id bigint; manager_job_id bigint; p_id bigint;
BEGIN
  SELECT id INTO reviewer_job_id FROM public.jobs WHERE job_name='مراجع' LIMIT 1;
  IF reviewer_job_id IS NULL THEN
    INSERT INTO public.jobs(job_name,is_active) VALUES('مراجع',true) RETURNING id INTO reviewer_job_id;
  END IF;

  FOREACH p_id IN ARRAY ARRAY[
    (SELECT id FROM public.permissions WHERE permission_key='review_exam_requests' LIMIT 1),
    (SELECT id FROM public.permissions WHERE permission_key='view_reviewed_exam_reviews' LIMIT 1),
    (SELECT id FROM public.permissions WHERE permission_key='view_unreviewed_exam_reviews' LIMIT 1),
    (SELECT id FROM public.permissions WHERE permission_key='adjust_exam_review_mark' LIMIT 1)
  ] LOOP
    IF p_id IS NOT NULL THEN
      INSERT INTO public.job_permissions(job_id,permission_id) SELECT reviewer_job_id,p_id WHERE NOT EXISTS (SELECT 1 FROM public.job_permissions WHERE job_id=reviewer_job_id AND permission_id=p_id);
    END IF;
  END LOOP;

  SELECT id INTO manager_job_id FROM public.jobs WHERE job_name='مدير' LIMIT 1;
  IF manager_job_id IS NOT NULL THEN
    FOREACH p_id IN ARRAY ARRAY[
      (SELECT id FROM public.permissions WHERE permission_key='review_exam_requests' LIMIT 1),
      (SELECT id FROM public.permissions WHERE permission_key='view_reviewed_exam_reviews' LIMIT 1),
      (SELECT id FROM public.permissions WHERE permission_key='view_unreviewed_exam_reviews' LIMIT 1),
      (SELECT id FROM public.permissions WHERE permission_key='adjust_exam_review_mark' LIMIT 1)
    ] LOOP
      IF p_id IS NOT NULL THEN
        INSERT INTO public.job_permissions(job_id,permission_id) VALUES(manager_job_id,p_id)
        ON CONFLICT DO NOTHING;
      END IF;
    END LOOP;
  END IF;
END $$;


