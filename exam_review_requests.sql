-- قراءة حالة الزر بشكل آمن من بوابة الطالب.
CREATE OR REPLACE FUNCTION public.get_exam_review_request_button_visibility()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE((SELECT show_create_request_button FROM public.exam_review_ui_settings WHERE id = true), true);
$$;

-- تغيير حالة الزر من شاشة مراجعة الامتحانات: المدير أو الموظف الممنوح له بند الصلاحية فقط.
CREATE OR REPLACE FUNCTION public.set_exam_review_request_button_visibility(
  p_employee_id bigint,
  p_visible boolean
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  allowed boolean := false;
  has_permission boolean := false;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM public.employees e
    LEFT JOIN public.jobs j ON j.id = e.job_id
    WHERE e.id = p_employee_id
      AND e.is_active IS DISTINCT FROM false
      AND (
        lower(coalesce(to_jsonb(e)->>'role','')) IN ('admin','manager','مدير')
        OR lower(coalesce(j.job_name,'')) = 'مدير'
      )
  ) INTO allowed;

  IF NOT allowed THEN
    SELECT EXISTS (
      SELECT 1
      FROM public.employees e
      JOIN public.job_permissions jp ON jp.job_id = e.job_id
      JOIN public.permissions p ON p.id = jp.permission_id
      WHERE e.id = p_employee_id
        AND e.is_active IS DISTINCT FROM false
        AND p.permission_key = 'manage_review_request_button_visibility'
        AND p.is_active IS DISTINCT FROM false
    ) INTO has_permission;
  END IF;

  IF NOT (allowed OR has_permission) THEN
    RAISE EXCEPTION 'لا تملك صلاحية إظهار أو إخفاء زر إنشاء طلب المراجعة';
  END IF;

  INSERT INTO public.exam_review_ui_settings (id, show_create_request_button, updated_by, updated_at)
  VALUES (true, COALESCE(p_visible, true), p_employee_id, now())
  ON CONFLICT (id) DO UPDATE
    SET show_create_request_button = EXCLUDED.show_create_request_button,
        updated_by = EXCLUDED.updated_by,
        updated_at = now();

  RETURN jsonb_build_object('success', true, 'visible', COALESCE(p_visible, true));
END;
$$;

INSERT INTO public.permissions(permission_key,permission_name,description,is_active)
VALUES ('manage_review_request_button_visibility','إظهار/إخفاء زر إنشاء طلب مراجعة للطلاب','التحكم في ظهور زر إنشاء طلب مراجعة في بوابة الطالب',true)
ON CONFLICT(permission_key) DO NOTHING;
