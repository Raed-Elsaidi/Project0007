-- يحدد دور المصحح بدون الاعتماد على اسم عمود إضافي.
CREATE OR REPLACE FUNCTION public.is_essay_grader(p_employee_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.employees e
    WHERE e.id = p_employee_id
      AND (
        lower(coalesce(to_jsonb(e)->>'role','')) IN ('grader','corrector','مصحح')
        OR coalesce(to_jsonb(e)->>'job_name','') = 'مصحح'
        OR coalesce(to_jsonb(e)->>'job','') = 'مصحح'
      )
  );
$$;

-- العلامة المقالية المعتمدة لسؤال واحد حسب القاعدة:
-- 2 متساويتان => نفس العلامة
-- مختلفتان => الثالثة
-- الثالثة تساوي إحدى الأوليين => الثالثة
-- الثلاث مختلفات => متوسط الثلاث مع التقريب للأعلى
CREATE OR REPLACE FUNCTION public.approved_essay_question_score(
  p_student_id bigint, p_exam_id bigint, p_question_id bigint
) RETURNS numeric
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE a numeric; b numeric; c numeric; n integer;
BEGIN
  SELECT count(*),
         max(score) FILTER (WHERE round_number=1),
         max(score) FILTER (WHERE round_number=2),
         max(score) FILTER (WHERE round_number=3)
    INTO n,a,b,c
  FROM public.essay_gradings
  WHERE student_id=p_student_id AND exam_id=p_exam_id AND question_id=p_question_id;

  IF n < 2 THEN RETURN NULL; END IF;
  IF a = b THEN RETURN a; END IF;
  IF n < 3 THEN RETURN NULL; END IF;
  IF c = a OR c = b THEN RETURN c; END IF;
  RETURN ceil((a+b+c)/3.0);
END;
$$;

CREATE OR REPLACE FUNCTION public.essay_manual_score(
  p_student_id bigint, p_exam_id bigint
) RETURNS numeric
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE(sum(public.approved_essay_question_score(sa.student_id, sa.exam_id, sa.question_id)),0)
  FROM public.student_answers sa
  JOIN public.questions q ON q.id = sa.question_id
  WHERE sa.student_id=p_student_id
    AND sa.exam_id=p_exam_id
    AND lower(coalesce(q.question_type,'')) IN ('essay','مقالي');
$$;

CREATE OR REPLACE FUNCTION public.essay_grading_status(
  p_student_id bigint, p_exam_id bigint
) RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT CASE
    WHEN EXISTS (
      SELECT 1 FROM public.student_answers sa JOIN public.questions q ON q.id=sa.question_id
      WHERE sa.student_id=p_student_id AND sa.exam_id=p_exam_id
        AND lower(coalesce(q.question_type,'')) IN ('essay','مقالي')
        AND public.approved_essay_question_score(sa.student_id,sa.exam_id,sa.question_id) IS NULL
    ) THEN 'pending_essay'
    WHEN EXISTS (
      SELECT 1 FROM public.student_answers sa JOIN public.questions q ON q.id=sa.question_id
      WHERE sa.student_id=p_student_id AND sa.exam_id=p_exam_id
        AND lower(coalesce(q.question_type,'')) IN ('essay','مقالي')
    ) THEN 'graded'
    ELSE 'no_essay'
  END;
$$;

CREATE OR REPLACE FUNCTION public.total_cheating_deduction(p_student_id bigint, p_exam_id bigint)
RETURNS numeric
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT COALESCE(sum(CASE WHEN action_taken='deduct' AND case_status='deducted' THEN COALESCE(deduction_marks,0) ELSE 0 END),0)
  FROM public.cheating_cases
  WHERE student_id=p_student_id AND exam_id=p_exam_id;
$$;

CREATE OR REPLACE FUNCTION public.has_failed_cheating_case(p_student_id bigint, p_exam_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT EXISTS (SELECT 1 FROM public.cheating_cases WHERE student_id=p_student_id AND exam_id=p_exam_id AND case_status='failed');
$$;

CREATE OR REPLACE FUNCTION public.finalize_exam_result(
  p_student_id bigint, p_exam_id bigint, p_subject_id bigint DEFAULT NULL, p_cycle_id bigint DEFAULT 1
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  s record;
  maxm numeric;
  auto numeric;
  manual numeric;
  deduct numeric;
  finalm numeric;
  avgm numeric;
  gs text;
  status text;
  resolved_subject_id bigint;
  overall jsonb;
BEGIN
  SELECT * INTO s FROM public.submissions
   WHERE student_id=p_student_id AND exam_id=p_exam_id
   ORDER BY COALESCE(submitted_at,created_at) DESC NULLS LAST, id DESC LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'لا توجد محاولة للطالب في هذا الامتحان';
  END IF;

  -- إذا لم يرسل المستدعي subject_id، نأخذه مباشرة من الامتحان.
  SELECT e.subject_id INTO resolved_subject_id
  FROM public.exams e
  WHERE e.id=p_exam_id;

  resolved_subject_id := COALESCE(p_subject_id, resolved_subject_id);

  auto := GREATEST(0,COALESCE(s.automatic_score,s.final_score,s.total_score,s.obtained_marks,0));
  maxm := GREATEST(0,COALESCE(s.total_marks, s.max_score, 0));
  manual := COALESCE(public.essay_manual_score(p_student_id,p_exam_id),0);
  deduct := COALESCE(public.total_cheating_deduction(p_student_id,p_exam_id),0);
  gs := public.essay_grading_status(p_student_id,p_exam_id);

  IF public.has_failed_cheating_case(p_student_id,p_exam_id) THEN
    finalm := 0;
  ELSE
    finalm := GREATEST(0,auto+manual-deduct);
    IF maxm > 0 THEN finalm := LEAST(finalm,maxm); END IF;
  END IF;

  avgm := CASE WHEN maxm>0 THEN round((finalm/maxm)*100,2) ELSE 0 END;
  status := CASE
              WHEN gs='pending_essay' THEN 'قيد التصحيح'
              WHEN avgm >= 50 THEN 'ناجح'
              ELSE 'راسب'
            END;

  INSERT INTO public.exam_results(
    student_id,exam_id,subject_id,cycle_id,automatic_score,manual_score,
    cheating_deduction,final_score,max_score,average,result_status,
    grading_status,approved_at,updated_at
  )
  VALUES(
    p_student_id,p_exam_id,resolved_subject_id,p_cycle_id,auto,manual,
    deduct,finalm,maxm,avgm,status,gs,
    CASE WHEN gs<>'pending_essay' THEN now() ELSE NULL END,now()
  )
  ON CONFLICT(student_id,exam_id) DO UPDATE SET
    subject_id=EXCLUDED.subject_id,
    cycle_id=EXCLUDED.cycle_id,
    automatic_score=EXCLUDED.automatic_score,
    manual_score=EXCLUDED.manual_score,
    cheating_deduction=EXCLUDED.cheating_deduction,
    final_score=EXCLUDED.final_score,
    max_score=EXCLUDED.max_score,
    average=EXCLUDED.average,
    result_status=EXCLUDED.result_status,
    grading_status=EXCLUDED.grading_status,
    approved_at=EXCLUDED.approved_at,
    updated_at=now();

  UPDATE public.submissions
  SET automatic_score=auto,
      manual_score=manual,
      cheating_deduction=deduct,
      final_score=finalm,
      obtained_marks=finalm,
      average=avgm,
      result_status=status,
      grading_status=gs,
      score_locked=(gs<>'pending_essay'),
      score_updated_at=now()
  WHERE id=s.id;

  -- حفظ/تحديث النتيجة النهائية للطالب في الجدول الرسمي.
  IF gs <> 'pending_essay' THEN
    overall := public.recalculate_student_final_result(p_student_id,p_cycle_id);
  END IF;

  RETURN jsonb_build_object(
    'student_id',p_student_id,
    'exam_id',p_exam_id,
    'subject_id',resolved_subject_id,
    'automatic_score',auto,
    'manual_score',manual,
    'cheating_deduction',deduct,
    'final_score',finalm,
    'max_score',maxm,
    'average',avgm,
    'result_status',status,
    'grading_status',gs,
    'student_final_result',overall
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_essay_grade(
  p_student_id bigint, p_exam_id bigint, p_question_id bigint, p_grader_id bigint, p_score numeric
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE maxm numeric; r integer; existing integer; result jsonb;
BEGIN
  IF NOT public.is_essay_grader(p_grader_id) THEN RAISE EXCEPTION 'هذا الحساب ليس مصححاً مخولاً'; END IF;
  SELECT COALESCE((to_jsonb(q)->>'mark')::numeric,(to_jsonb(q)->>'points')::numeric,0) INTO maxm FROM public.questions q WHERE q.id=p_question_id;
  IF maxm IS NULL THEN RAISE EXCEPTION 'السؤال غير موجود'; END IF;
  IF p_score < 0 OR p_score > maxm THEN RAISE EXCEPTION 'العلامة خارج الحد المسموح'; END IF;
  IF EXISTS(SELECT 1 FROM public.essay_gradings WHERE student_id=p_student_id AND exam_id=p_exam_id AND question_id=p_question_id AND grader_id=p_grader_id) THEN
    RAISE EXCEPTION 'لا يمكنك تصحيح السؤال نفسه مرتين';
  END IF;
  SELECT count(*) INTO existing FROM public.essay_gradings WHERE student_id=p_student_id AND exam_id=p_exam_id AND question_id=p_question_id;
  IF existing >= 3 THEN RAISE EXCEPTION 'اكتمل عدد المصححين لهذا السؤال'; END IF;
  r := existing + 1;
  INSERT INTO public.essay_gradings(student_id,exam_id,question_id,grader_id,round_number,score,max_score) VALUES(p_student_id,p_exam_id,p_question_id,p_grader_id,r,p_score,maxm);
  result := public.finalize_exam_result(p_student_id,p_exam_id,NULL,1);
  RETURN jsonb_build_object('round',r,'approved_score',public.approved_essay_question_score(p_student_id,p_exam_id,p_question_id),'result',result);
END;
$$;

CREATE OR REPLACE FUNCTION public.get_essay_grading_queue(p_grader_id bigint)
RETURNS TABLE(student_id bigint, exam_id bigint, question_id bigint, question_text text, student_answer text, max_score numeric)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.is_essay_grader(p_grader_id) THEN RAISE EXCEPTION 'هذا الحساب ليس مصححاً'; END IF;
  RETURN QUERY
  SELECT sa.student_id, sa.exam_id, sa.question_id,
         coalesce(to_jsonb(q)->>'question_text','')::text,
         coalesce(to_jsonb(sa)->>'student_answer',to_jsonb(sa)->>'answer_text',to_jsonb(sa)->>'answer','')::text,
         coalesce((to_jsonb(q)->>'mark')::numeric,(to_jsonb(q)->>'points')::numeric,0)
  FROM public.student_answers sa
  JOIN public.questions q ON q.id=sa.question_id
  WHERE lower(coalesce(q.question_type,'')) IN ('essay','مقالي')
    AND NOT EXISTS (
      SELECT 1 FROM public.essay_gradings eg
      WHERE eg.student_id=sa.student_id AND eg.exam_id=sa.exam_id AND eg.question_id=sa.question_id AND eg.grader_id=p_grader_id
    )
    AND public.approved_essay_question_score(sa.student_id,sa.exam_id,sa.question_id) IS NULL
  ORDER BY sa.exam_id, sa.question_id, sa.student_id;
END;
$$;

