CREATE OR REPLACE FUNCTION public.grade12_normalize(value text)
RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT regexp_replace(
    replace(replace(replace(replace(replace(lower(coalesce(value,'')),
      'أ','ا'),'إ','ا'),'آ','ا'),'ة','ه'),'ى','ي'),
    '[[:space:]]+', ' ', 'g'
  );
$$;

CREATE OR REPLACE FUNCTION public.recalculate_student_final_result(
  p_student_id bigint, p_cycle_id bigint DEFAULT 1
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_branch_name text;
  v_total numeric := 0;
  v_failed integer := 0;
  v_counted integer := 0;
  v_average numeric := 0;
  v_status text := 'راسب';
BEGIN
  SELECT COALESCE(
    to_jsonb(b)->>'branch_name',
    to_jsonb(b)->>'name',
    to_jsonb(b)->>'branch',
    ''
  )
  INTO v_branch_name
  FROM public.students st
  LEFT JOIN public.branches b ON b.id=st.branch_id
  WHERE st.id=p_student_id;

  /*
   * نبني آخر علامة معتمدة لكل مادة.
   * إذا كان subject_id في سجل قديم NULL، نأخذه من exams.subject_id.
   * العلامة المختارة من المواد الاختيارية هي العلامة الفعلية الأعلى للطالب.
   */
  WITH exam_subject_results AS (
    SELECT
      er.student_id,
      er.cycle_id,
      COALESCE(
        er.subject_id,
        (SELECT e.subject_id FROM public.exams e WHERE e.id=er.exam_id)
      ) AS subject_id,
      er.final_score,
      er.updated_at,
      er.id,
      row_number() OVER (
        PARTITION BY er.student_id, er.cycle_id,
                     COALESCE(er.subject_id,
                       (SELECT e.subject_id FROM public.exams e WHERE e.id=er.exam_id))
        ORDER BY er.updated_at DESC, er.id DESC
      ) AS rn
    FROM public.exam_results er
    WHERE er.student_id=p_student_id
      AND er.cycle_id=p_cycle_id
      AND er.grading_status <> 'pending_essay'
  ),
  latest AS (
    SELECT * FROM exam_subject_results WHERE rn=1
  ),
  all_subjects AS (
    SELECT
      s.id AS subject_id,
      public.grade12_normalize(
        COALESCE(
          to_jsonb(s)->>'subject_name',
          to_jsonb(s)->>'name',
          to_jsonb(s)->>'title',
          to_jsonb(s)->>'subject',
          ''
        )
      ) AS subject_name,
      COALESCE(
        NULLIF(to_jsonb(s)->>'minimum_mark','')::numeric,
        NULLIF(to_jsonb(s)->>'min_mark','')::numeric,
        NULLIF(to_jsonb(s)->>'min_marks','')::numeric,
        NULLIF(to_jsonb(s)->>'minimum_marks','')::numeric,
        0
      ) AS min_mark,
      COALESCE(
        NULLIF(to_jsonb(s)->>'maximum_mark','')::numeric,
        NULLIF(to_jsonb(s)->>'max_mark','')::numeric,
        NULLIF(to_jsonb(s)->>'max_marks','')::numeric,
        NULLIF(to_jsonb(s)->>'maximum_marks','')::numeric,
        NULLIF(to_jsonb(s)->>'total_marks','')::numeric,
        NULLIF(to_jsonb(s)->>'total_mark','')::numeric,
        0
      ) AS max_mark,
      COALESCE(l.final_score,0) AS mark
    FROM public.subjects s
    JOIN public.students st
      ON st.id=p_student_id
     AND s.branch_id=st.branch_id
    LEFT JOIN latest l ON l.subject_id=s.id
  ),
  classified AS (
    SELECT
      a.*,
      CASE
        /* العلمي */
        WHEN public.grade12_normalize(v_branch_name) LIKE '%علمي%'
         AND (
           a.subject_name LIKE '%كيمياء%' OR a.subject_name LIKE '%احياء%' OR
           a.subject_name LIKE '%تربيه اسلاميه%' OR a.subject_name LIKE '%اسلاميه%' OR
           a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'scientific_optional'
        /* الأدبي */
        WHEN public.grade12_normalize(v_branch_name) LIKE '%ادبي%'
         AND (
           a.subject_name LIKE '%جغرافيا%' OR a.subject_name LIKE '%ثقافه علميه%' OR
           a.subject_name LIKE '%تربيه اسلاميه%' OR a.subject_name LIKE '%اسلاميه%' OR
           a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'literary_optional'
        /* الريادة والأعمال */
        WHEN (public.grade12_normalize(v_branch_name) LIKE '%رياده%'
           OR public.grade12_normalize(v_branch_name) LIKE '%اعمال%')
         AND (
           a.subject_name LIKE '%اداره واقتصاد%' OR a.subject_name LIKE '%مشاريع صغيره%' OR
           a.subject_name LIKE '%تربيه اسلاميه%' OR a.subject_name LIKE '%اسلاميه%' OR
           a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'business_optional'
        /* الشرعي */
        WHEN public.grade12_normalize(v_branch_name) LIKE '%شرعي%'
         AND (
           a.subject_name LIKE '%فقه واصوله%' OR a.subject_name LIKE '%عقيده%' OR
           a.subject_name LIKE '%تكنولوجيا%' OR a.subject_name LIKE '%تربيه اسلاميه%' OR
           a.subject_name LIKE '%اسلاميه%'
         ) THEN 'sharia_optional'
        /* الصناعي */
        WHEN public.grade12_normalize(v_branch_name) LIKE '%صناعي%'
         AND (
           a.subject_name LIKE '%فيزياء%' OR a.subject_name LIKE '%رسم صناعي%' OR
           a.subject_name LIKE '%تربيه اسلاميه%' OR a.subject_name LIKE '%اسلاميه%' OR
           a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'industrial_optional'
        /* الزراعي */
        WHEN public.grade12_normalize(v_branch_name) LIKE '%زراعي%'
         AND (
           a.subject_name LIKE '%كيمياء%' OR a.subject_name LIKE '%احياء%' OR
           a.subject_name LIKE '%رياضيات%' OR a.subject_name LIKE '%تربيه اسلاميه%' OR
           a.subject_name LIKE '%اسلاميه%' OR a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'agricultural_optional'
        /* الفندقي */
        WHEN public.grade12_normalize(v_branch_name) LIKE '%فندقي%'
         AND (
           a.subject_name LIKE '%اداره سياحه%' OR a.subject_name LIKE '%اداره سياحيه%' OR
           a.subject_name LIKE '%سياحه%' OR a.subject_name LIKE '%رياضيات%' OR
           a.subject_name LIKE '%تربيه اسلاميه%' OR a.subject_name LIKE '%اسلاميه%' OR
           a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'hotel_optional'
        /* الاقتصاد المنزلي */
        WHEN (public.grade12_normalize(v_branch_name) LIKE '%اقتصاد منزلي%')
         AND (
           a.subject_name LIKE '%كيمياء%' OR a.subject_name LIKE '%احياء%' OR
           a.subject_name LIKE '%اداره%' OR a.subject_name LIKE '%تربيه اسلاميه%' OR
           a.subject_name LIKE '%اسلاميه%' OR a.subject_name LIKE '%تكنولوجيا%'
         ) THEN 'home_optional'
        ELSE 'mandatory_or_other'
      END AS optional_group
    FROM all_subjects a
  ),
  selected AS (
    /*
     * المواد الإجبارية تُحتسب دائماً.
     * في المجموعات الاختيارية نأخذ أعلى علامة فعلية حصل عليها الطالب.
     * لا توجد مقارنة بالنسب عند الاختيار.
     */
    SELECT c.*
    FROM classified c
    WHERE
      CASE
        WHEN public.grade12_normalize(v_branch_name) LIKE '%علمي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%رياضيات%' OR c.subject_name LIKE '%فيزياء%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%كيمياء%' OR x.subject_name LIKE '%احياء%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          ) OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%تربيه اسلاميه%' OR x.subject_name LIKE '%اسلاميه%' OR
                  x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%ادبي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%رياضيات%' OR c.subject_name LIKE '%تاريخ%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%جغرافيا%' OR x.subject_name LIKE '%ثقافه علميه%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          ) OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%تربيه اسلاميه%' OR x.subject_name LIKE '%اسلاميه%' OR
                  x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%رياده%'
          OR public.grade12_normalize(v_branch_name) LIKE '%اعمال%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%رياضيات%' OR c.subject_name LIKE '%محاسبه%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%اداره واقتصاد%' OR x.subject_name LIKE '%مشاريع صغيره%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          ) OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%تربيه اسلاميه%' OR x.subject_name LIKE '%اسلاميه%' OR
                  x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%شرعي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%رياضيات%' OR c.subject_name LIKE '%قران%' OR c.subject_name LIKE '%حديث%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%فقه واصوله%' OR x.subject_name LIKE '%عقيده%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          ) OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%تكنولوجيا%' OR x.subject_name LIKE '%تربيه اسلاميه%' OR
                  x.subject_name LIKE '%اسلاميه%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 1
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%صناعي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%رياضيات صناعيه%' OR c.subject_name LIKE '%تدريب عملي%' OR
          c.subject_name LIKE '%علوم مهنيه%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%فيزياء%' OR x.subject_name LIKE '%رسم صناعي%' OR
                  x.subject_name LIKE '%تربيه اسلاميه%' OR x.subject_name LIKE '%اسلاميه%' OR
                  x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 2
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%زراعي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%تدريب عملي%' OR c.subject_name LIKE '%علوم زراعيه%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%كيمياء%' OR x.subject_name LIKE '%احياء%' OR
                  x.subject_name LIKE '%رياضيات%' OR x.subject_name LIKE '%تربيه اسلاميه%' OR
                  x.subject_name LIKE '%اسلاميه%' OR x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 2
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%فندقي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%تدريب عملي%' OR c.subject_name LIKE '%علوم فندقيه%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%اداره سياحه%' OR x.subject_name LIKE '%اداره سياحيه%' OR
                  x.subject_name LIKE '%سياحه%' OR x.subject_name LIKE '%رياضيات%' OR
                  x.subject_name LIKE '%تربيه اسلاميه%' OR x.subject_name LIKE '%اسلاميه%' OR
                  x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 2
          )

        WHEN public.grade12_normalize(v_branch_name) LIKE '%اقتصاد منزلي%' THEN
          c.subject_name LIKE '%عربي%' OR c.subject_name LIKE '%انجليزي%' OR
          c.subject_name LIKE '%تدريب عملي%' OR c.subject_name LIKE '%علوم مهنيه%' OR
          c.subject_id IN (
            SELECT x.subject_id FROM classified x
            WHERE x.subject_name LIKE '%كيمياء%' OR x.subject_name LIKE '%احياء%' OR
                  x.subject_name LIKE '%اداره%' OR x.subject_name LIKE '%تربيه اسلاميه%' OR
                  x.subject_name LIKE '%اسلاميه%' OR x.subject_name LIKE '%تكنولوجيا%'
            ORDER BY x.mark DESC, x.subject_id LIMIT 2
          )

        ELSE TRUE
      END
  ),
  totals AS (
    SELECT
      COALESCE(SUM(mark),0) AS total_mark,
      COUNT(*) AS counted_count
    FROM selected
  ),
  failures AS (
    SELECT COUNT(*) AS failed_count
    FROM all_subjects
    WHERE mark < min_mark
  )
  SELECT
    t.total_mark,
    t.counted_count,
    f.failed_count
  INTO v_total, v_counted, v_failed
  FROM totals t CROSS JOIN failures f;

  -- جميع الفروع الثمانية تعتمد 700 في مقام المعدل.
  v_average := round((COALESCE(v_total,0) / 700.0) * 100, 2);

  IF v_failed > 4 THEN
    v_status := 'راسب';
  ELSIF COALESCE(v_total,0) < 350 OR v_failed BETWEEN 1 AND 4 THEN
    v_status := 'مكمل';
  ELSE
    v_status := 'ناجح';
  END IF;

  INSERT INTO public.student_final_results(
    student_id,cycle_id,total_score,maximum_score,average,
    result_status,failed_subjects,counted_subjects,updated_at
  )
  VALUES(
    p_student_id,p_cycle_id,COALESCE(v_total,0),700,v_average,
    v_status,COALESCE(v_failed,0),COALESCE(v_counted,0),now()
  )
  ON CONFLICT(student_id,cycle_id) DO UPDATE SET
    total_score=EXCLUDED.total_score,
    maximum_score=EXCLUDED.maximum_score,
    average=EXCLUDED.average,
    result_status=EXCLUDED.result_status,
    failed_subjects=EXCLUDED.failed_subjects,
    counted_subjects=EXCLUDED.counted_subjects,
    updated_at=now();

  UPDATE public.students
  SET final_total=COALESCE(v_total,0),
      final_average=v_average,
      final_result=v_status,
      result_updated_at=now()
  WHERE id=p_student_id;

  RETURN jsonb_build_object(
    'student_id',p_student_id,
    'cycle_id',p_cycle_id,
    'total_score',COALESCE(v_total,0),
    'maximum_score',700,
    'average',v_average,
    'result_status',v_status,
    'failed_subjects',COALESCE(v_failed,0),
    'counted_subjects',COALESCE(v_counted,0)
  );
END;
$$;

